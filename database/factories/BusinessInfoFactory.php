<?php

namespace Database\Factories;

use App\Models\BusinessInfo;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * Fake business profile. Images point at placeholder files committed in public/.
 */
class BusinessInfoFactory extends Factory
{
    protected $model = BusinessInfo::class;

    public function definition(): array
    {
        return [
            'business_name' => 'Demo Business '.$this->faker->unique()->numberBetween(1, 999),
            'business_logo' => '1730854574a single logo.png',
            'business_image' => '1730854574a single logo.png',
            'year' => $this->faker->numberBetween(2015, 2023),
            'business_type' => $this->faker->randomElement(['Restaurant', 'Print and Merch Shop']),
            'location' => $this->faker->numberBetween(1, 999).' Demo Street, Sample City',
            'description' => 'Demo business profile generated by the seeders.',
        ];
    }
}
