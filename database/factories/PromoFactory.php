<?php

namespace Database\Factories;

use Illuminate\Database\Eloquent\Factories\Factory;

class PromoFactory extends Factory
{
    protected $model = \App\Models\Promo::class;

    /**
     * promo_image stays empty: the views show no image instead of a broken one.
     */
    public function definition()
    {
        $start = $this->faker->dateTimeBetween('-11 months', '-1 week');

        return [
            'title' => $this->faker->randomElement(['Rainy Day Combo', 'Buy 1 Take 1 Coffee', 'Student Meal Deal', 'Weekend Family Bundle', 'Merienda Treat']),
            'promo_image' => '',
            'start_date' => $start->format('Y-m-d'),
            'end_date' => (clone $start)->modify('+14 days')->format('Y-m-d'),
            'sales_before' => $this->faker->numberBetween(150000, 250000),
            'sales_after' => $this->faker->numberBetween(160000, 300000),
            'description' => 'Demo promo generated by the seeders.',
            'dishes_available' => implode(', ', $this->faker->randomElements(['Iced Latte', 'Chicken Adobo Bowl', 'Carbonara', 'Mango Float', 'Clubhouse Sandwich'], 2)),
        ];
    }
}
